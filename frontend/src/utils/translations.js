/**
 * Returns dictionary for given language code with fallback to Hindi, then English.
 */
export function getDictionary(lang = "en") {
  const code = (lang || "en").split("-")[0];
  const selected = TRANSLATIONS[code] || TRANSLATIONS.en;
  // Merge with English fallback so no key is ever undefined
  return { ...TRANSLATIONS.en, ...selected };
}

